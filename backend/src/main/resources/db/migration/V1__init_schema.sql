-- FinTrack: єдина база даних монолітного застосунку

-- ============ Модуль користувача та синхронізації ============
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL,
    password_hash   VARCHAR(255),
    display_name    VARCHAR(100) NOT NULL,
    email_verified  BOOLEAN      NOT NULL DEFAULT FALSE,
    auth_provider   VARCHAR(20)  NOT NULL DEFAULT 'LOCAL',
    google_id       VARCHAR(255),
    currency        VARCHAR(3)   NOT NULL DEFAULT 'UAH',
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE email_verification_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_email_tokens_hash UNIQUE (token_hash)
);

-- Сесія = окремий пристрій користувача (refresh-токен ротується в межах сесії)
CREATE TABLE user_sessions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    refresh_token_hash  VARCHAR(64)  NOT NULL,
    device_name         VARCHAR(255),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked             BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_sessions_token UNIQUE (refresh_token_hash)
);
CREATE INDEX idx_sessions_user ON user_sessions (user_id);

-- ============ Модуль обліку операцій ============
CREATE TABLE accounts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name             VARCHAR(100)   NOT NULL,
    type             VARCHAR(20)    NOT NULL,
    initial_balance  NUMERIC(19, 2) NOT NULL DEFAULT 0,
    color            VARCHAR(9)     NOT NULL,
    archived         BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT         NOT NULL DEFAULT 0
);
CREATE INDEX idx_accounts_user ON accounts (user_id);

-- ============ Модуль бюджетування та категорій ============
CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    parent_id   BIGINT       REFERENCES categories (id),
    name        VARCHAR(100) NOT NULL,
    type        VARCHAR(10)  NOT NULL,
    icon        VARCHAR(50)  NOT NULL,
    color       VARCHAR(9)   NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX idx_categories_user ON categories (user_id);

CREATE TABLE recurring_transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name            VARCHAR(100)   NOT NULL,
    type            VARCHAR(10)    NOT NULL,
    amount          NUMERIC(19, 2) NOT NULL,
    account_id      BIGINT         NOT NULL REFERENCES accounts (id),
    category_id     BIGINT         NOT NULL REFERENCES categories (id),
    note            VARCHAR(500),
    frequency       VARCHAR(10)    NOT NULL,
    interval_count  INT            NOT NULL DEFAULT 1,
    start_date      DATE           NOT NULL,
    next_date       DATE           NOT NULL,
    end_date        DATE,
    auto_create     BOOLEAN        NOT NULL DEFAULT TRUE,
    active          BOOLEAN        NOT NULL DEFAULT TRUE,
    reminded_for    DATE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT chk_recurring_amount CHECK (amount > 0)
);
CREATE INDEX idx_recurring_user ON recurring_transactions (user_id);
CREATE INDEX idx_recurring_due ON recurring_transactions (active, next_date);

CREATE TABLE transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type            VARCHAR(10)    NOT NULL,
    amount          NUMERIC(19, 2) NOT NULL,
    occurred_on     DATE           NOT NULL,
    account_id      BIGINT         NOT NULL REFERENCES accounts (id),
    to_account_id   BIGINT         REFERENCES accounts (id),
    category_id     BIGINT         REFERENCES categories (id),
    note            VARCHAR(500),
    recurring_id    BIGINT         REFERENCES recurring_transactions (id) ON DELETE SET NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT chk_transactions_amount CHECK (amount > 0)
);
CREATE INDEX idx_transactions_user_date ON transactions (user_id, occurred_on);
CREATE INDEX idx_transactions_user_category ON transactions (user_id, category_id);
CREATE INDEX idx_transactions_user_account ON transactions (user_id, account_id);

CREATE TABLE budgets (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id      BIGINT         NOT NULL REFERENCES categories (id),
    amount           NUMERIC(19, 2) NOT NULL,
    rollover         BOOLEAN        NOT NULL DEFAULT FALSE,
    alert_threshold  INT            NOT NULL DEFAULT 80,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_budgets_user_category UNIQUE (user_id, category_id),
    CONSTRAINT chk_budgets_amount CHECK (amount > 0)
);

-- Місячний період бюджету: ліміт + перенесений з попереднього місяця залишок
CREATE TABLE budget_periods (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    budget_id          BIGINT         NOT NULL REFERENCES budgets (id) ON DELETE CASCADE,
    period_start       DATE           NOT NULL,
    limit_amount       NUMERIC(19, 2) NOT NULL,
    carried_over       NUMERIC(19, 2) NOT NULL DEFAULT 0,
    warning_notified   BOOLEAN        NOT NULL DEFAULT FALSE,
    exceeded_notified  BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_budget_periods UNIQUE (budget_id, period_start)
);

CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type        VARCHAR(30)   NOT NULL,
    title       VARCHAR(200)  NOT NULL,
    message     VARCHAR(1000) NOT NULL,
    is_read     BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_notifications_user ON notifications (user_id, created_at);
